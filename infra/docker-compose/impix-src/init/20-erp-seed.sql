SELECT 'MO' || to_char(d,'YYMMDD') || lpad(n::text,3,'0'),
       1,
       CASE n WHEN 1 THEN 'EWP-A100' ELSE 'EWP-B200' END,
       '1200',
       CASE n WHEN 1 THEN 'AL01' ELSE 'AL02' END,
       CASE n WHEN 1 THEN 'R-EWP-A100' ELSE 'R-EWP-B200' END,
       CASE n WHEN 1 THEN '002' ELSE '001' END,
       CASE n WHEN 1 THEN 400 ELSE 200 END,
       'EA',
       to_char(d,'YYYYMMDD'),
       to_char(d + 1,'YYYYMMDD'),
       to_char(d + 3,'YYYYMMDD'),
       'SO' || to_char(d - 7,'YYMMDD') || lpad(n::text,3,'0'),
       1,
       CASE WHEN d >= DATE '2026-10-21' THEN '20'
            WHEN d >= DATE '2026-10-19' THEN '30'
            ELSE '40' END,
       (d - 2)::timestamp + time '16:30',
       '20220081'
FROM generate_series(DATE '2026-09-21', DATE '2026-10-25', interval '1 day') AS g(d0)
CROSS JOIN LATERAL (SELECT g.d0::date AS d) x
CROSS JOIN generate_series(1,2) AS n
WHERE extract(isodow FROM d) <> 7;

